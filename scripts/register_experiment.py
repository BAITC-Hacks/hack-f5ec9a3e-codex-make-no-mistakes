"""Archive a completed run and rebuild experiments/INDEX.md; standard library only."""
from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import json
import math
import re
import shutil
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "experiments/runs"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def phase(value):
    return {"validation_2025": "development_2025", "holdout_2026": "retrospective_2026"}.get(value, value)


def inspect_predictions(source, models, metrics):
    targets, seen, groups = {}, set(), defaultdict(lambda: [0, 0., 0., 0., 0.])
    with (source / "predictions.csv").open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            key = (row["supplier"], row["sku"], row["unit"], row["origin"], int(row.get("horizon_days", row.get("horizon"))))
            if key[3][:4] not in ("2025", "2026"):
                raise ValueError("This registry protocol only labels 2025 development and 2026 retrospective data")
            actual = float(row["actual"])
            if not math.isfinite(actual) or actual < 0:
                raise ValueError("Invalid actual quantity")
            if key in targets and targets[key] != actual:
                raise ValueError("Different actual quantities for the same forecast key")
            targets[key] = actual
            entries = [(row["model_id"], float(row["forecast"]))] if "model_id" in row else [(m, float(row[m])) for m in models]
            for model, predicted in entries:
                if model not in models:
                    continue
                if not math.isfinite(predicted) or predicted < 0 or (model, key) in seen:
                    raise ValueError("Invalid or duplicate prediction")
                seen.add((model, key))
                group = ("development_2025" if key[3].startswith("2025") else "retrospective_2026", key[0], key[2], key[4], model)
                total = groups[group]
                error = predicted - actual
                for i, v in enumerate((1, actual, abs(error), error, max(-error, 0))):
                    total[i] += v
    for model in models:
        if sum(m == model for m, _ in seen) != len(targets):
            raise ValueError(f"Incomplete cohort for {model}")
    matched = set()
    for metric in metrics:
        if metric["segment"] != "all" or metric["model"] not in models:
            continue
        key = (phase(metric["phase"]), metric["supplier"], metric["unit"], int(metric["horizon"]), metric["model"])
        n, actual, absolute, bias, under = groups[key]
        if n != metric["n"]:
            raise ValueError(f"Metric row count mismatch: {key}")
        for name, value in (("wape_pct", absolute), ("bias_pct", bias), ("underforecast_pct", under)):
            expected = 100 * value / actual if actual else None
            if (expected is None) != (metric[name] is None) or (expected is not None and abs(expected - metric[name]) > 0.000501):
                raise ValueError(f"Metric mismatch: {key} {name}")
        if "mae" in metric and abs(metric["mae"] - absolute / n) > 1e-7:
            raise ValueError(f"MAE mismatch: {key}")
        metric["mae"] = absolute / n
        matched.add(key)
    if matched != set(groups):
        raise ValueError("Some forecast groups have no metrics")
    canonical = json.dumps(sorted((list(k), v) for k, v in targets.items()), ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(canonical.encode()).hexdigest(), len(targets), len(groups)


def rebuild_index():
    manifests = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(RUNS.glob("*/manifest.json"))]
    lines = ["# Experiment comparison / Сравнение экспериментов", "",
             "Generated by `python scripts/register_experiment.py --refresh`. See [workflow](README.md).",
             "", "2026 is retrospective. Lower WAPE does not imply better inventory outcomes. No automatic winner is selected.", ""]
    comparisons = []
    suites = defaultdict(list)
    for manifest in manifests:
        suites[manifest["comparison_signature"]].append(manifest)
    for signature, runs in suites.items():
        lines += [f"## Matching data/targets: `{signature[:12]}`", "",
                  f"{runs[0]['target_rows']:,} common forecast keys. Different signatures are shown separately.", "",
                  "| Run | Models | Reproduction / notes |", "| --- | --- | --- |"]
        for run in runs:
            lines.append(f"| [{run['run_id']}](runs/{run['run_id']}/manifest.json) | {', '.join(run['models'])} | {run['notes'].replace('|', '/')} |")
        groups = sorted({(m["supplier"], m["unit"]) for run in runs for m in run["metrics"]})
        for metric, title, period in (("wape_pct", "28-day WAPE (%), development 2025", "development_2025"),
                                      ("wape_pct", "28-day WAPE (%), retrospective 2026", "retrospective_2026"),
                                      ("bias_pct", "28-day bias (%), retrospective 2026", "retrospective_2026")):
            lines += ["", f"### {title}", "",
                      "| Run / model | " + " | ".join(f"{s} / {u}" for s, u in groups) + " |",
                      "| --- | " + " | ".join("---:" for _ in groups) + " |"]
            for run in runs:
                for model in run["models"]:
                    values = {(m["supplier"], m["unit"]): m[metric] for m in run["metrics"]
                              if phase(m["phase"]) == period and m["segment"] == "all"
                              and m["horizon"] == 28 and m["model"] == model}
                    display = ["—" if values.get(g) is None else f"{values[g]:.3f}" for g in groups]
                    lines.append(f"| {run['name']} / {model} | " + " | ".join(display) + " |")
        for run in runs:
            for m in run["metrics"]:
                if m["model"] in run["models"]:
                    comparisons.append({"run_id": run["run_id"], "comparison_signature": signature,
                                        **{k: m.get(k) for k in ("phase", "supplier", "unit", "horizon", "segment", "model", "n", "wape_pct", "bias_pct", "underforecast_pct", "mae")}})
    (ROOT / "experiments/INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if comparisons:
        with (ROOT / "experiments/comparison.csv").open("w", encoding="utf-8-sig", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(comparisons[0]))
            writer.writeheader()
            writer.writerows(comparisons)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?")
    parser.add_argument("--name")
    parser.add_argument("--models", nargs="+")
    parser.add_argument("--scripts", nargs="+", default=[])
    parser.add_argument("--notes", default="")
    parser.add_argument("--command", default="")
    parser.add_argument("--refresh", action="store_true")
    args = parser.parse_args()
    if args.refresh:
        rebuild_index()
        return
    if not args.source or not args.name or not re.fullmatch(r"[a-z0-9-]+", args.name) or not args.models:
        parser.error("source, --name (lowercase slug), and --models are required")
    source = (ROOT / args.source).resolve()
    summary = json.loads((source / "results.json").read_text(encoding="utf-8"))
    target_hash, count, checked = inspect_predictions(source, args.models, summary["metrics"])
    source_hashes = sorted((s["supplier"], s["sha256"]) for s in summary["source_files"])
    signature = hashlib.sha256(json.dumps([source_hashes, target_hash], separators=(",", ":")).encode()).hexdigest()
    script_paths = [(ROOT / p).resolve() for p in args.scripts]
    for path in script_paths:
        expected = summary.get("script_sha256", {}).get(path.name)
        if expected and digest(path) != expected:
            raise ValueError(f"Script changed since run: {path.name}")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    run_id = f"{stamp}-{args.name}"
    destination = RUNS / run_id
    destination.mkdir(parents=True, exist_ok=False)
    hashes = {}
    for path in sorted(source.iterdir()):
        if path.suffix not in (".json", ".csv"):
            continue
        target = destination / (path.name + ".gz" if path.suffix == ".csv" else path.name)
        if path.suffix == ".csv":
            with path.open("rb") as inp, gzip.open(target, "wb") as out:
                shutil.copyfileobj(inp, out)
        else:
            shutil.copy2(path, target)
        hashes[target.name] = {"archived_sha256": digest(target), "original_sha256": digest(path)}
    code = destination / "code"
    code.mkdir()
    for path in script_paths:
        shutil.copy2(path, code / path.name)
        hashes[f"code/{path.name}"] = {"archived_sha256": digest(path)}
    manifest = {"schema_version": 1, "run_id": run_id, "name": args.name,
                "archived_at_utc": stamp, "source_directory": str(source.relative_to(ROOT)),
                "models": args.models, "notes": args.notes, "reproduce_command": args.command,
                "comparison_signature": signature, "target_sha256": target_hash, "target_rows": count,
                "verified_full_cohort_metric_groups": checked, "source_hashes": source_hashes,
                "code_provenance": "matched recorded hashes" if summary.get("script_sha256") else "captured at registration; original run did not record code hashes",
                "recorded_environment": summary.get("environment", "not recorded by original run"),
                "elapsed_seconds": summary.get("elapsed_seconds"), "files": hashes,
                "metrics": [m for m in summary["metrics"] if m["model"] in args.models]}
    (destination / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    rebuild_index()
    print(json.dumps({"run_id": run_id, "target_rows": count, "verified_groups": checked, "comparison_signature": signature}))


if __name__ == "__main__":
    main()
